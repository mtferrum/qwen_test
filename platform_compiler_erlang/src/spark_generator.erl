-spec generate_source_table(map(), [map()], map()) -> string().
generate_source_table(Table, Sources, State) ->
    Name = maps:get(name, Table),
    Connector = find_connector(Name, Sources),
    
    case Connector of
        undefined ->
            create_temp_view(Table);
        _ ->
            ConnType = binary_to_list(maps:get(<<"type">>, Connector, <<"hdfs">>)),
            ConnConfig = maps:get(<<"config">>, Connector, #{}),
            case ConnType of
                "kafka" -> generate_kafka_source(Table, ConnConfig, State);
                "hdfs" -> generate_file_source(Table, ConnConfig, State);
                "s3" -> generate_file_source(Table, ConnConfig, State);
                _ -> "-- Unsupported source type: " ++ ConnType
            end
    end.

-spec generate_sink_table(map(), map()) -> string().
generate_sink_table(Sink, State) ->
    Name = binary_to_list(maps:get(<<"name">>, Sink, <<"">>)),
    ConnType = binary_to_list(maps:get(<<"type">>, Sink, <<"hdfs">>)),
    ConnConfig = maps:get(<<"config">>, Sink, #{}),
    
    case ConnType of
        "kafka" -> generate_kafka_sink(Name, ConnConfig);
        "hdfs" -> generate_file_sink(Name, ConnConfig);
        "s3" -> generate_file_sink(Name, ConnConfig);
        _ -> "-- Unsupported sink type: " ++ ConnType
    end.

-spec generate_kafka_source(map(), map(), map()) -> string().
generate_kafka_source(Table, Config, State) ->
    Name = maps:get(name, Table),
    Columns = string:join([K ++ " " ++ base_generator:format_type(V) || {K, V} <- maps:to_list(maps:get(columns, Table, #{}))], ", "),
    Servers = string:join(binary_to_list(maps:get(<<"bootstrap_servers">>, Config, [<<"localhost:9092">>])), ","),
    Topic = binary_to_list(maps:get(<<"topic">>, Config, list_to_binary(Name))),
    Format = binary_to_list(maps:get(<<"format">>, Config, <<"json">>)),
    
    Mode = maps:get(mode, State, "batch"),
    
    case Mode of
        "streaming" ->
            Watermark = case maps:get(stream_config, Table, undefined) of
                undefined -> "";
                SC -> 
                    TimeAttr = maps:get(time_attribute, SC, ""),
                    WmInterval = maps:get(watermark, SC, "10 seconds"),
                    ".withWatermark(\"" ++ TimeAttr ++ "\", \"" ++ WmInterval ++ "\")"
            end,
            io_lib:format(
"-- Kafka Source: ~s
CREATE OR REPLACE TEMPORARY VIEW ~s
USING kafka
OPTIONS (
  kafka.bootstrap.servers \"~s\",
  subscribe \"~s\",
  startingOffsets \"latest\",
  failOnDataLoss \"false\"
);

-- Parse Kafka payload
SELECT FROM_JSON(CAST(value AS STRING), \"~s\") AS data
FROM ~s_raw~s;", [Name, Name, Servers, Topic, Columns, Name, Watermark]);
        _ ->
            io_lib:format(
"-- Kafka Source (Batch): ~s
-- Note: Batch mode reads all available data from Kafka
CREATE OR REPLACE TEMPORARY VIEW ~s
USING kafka
OPTIONS (
  kafka.bootstrap.servers \"~s\",
  subscribe \"~s\",
  startingOffsets \"earliest\"
);", [Name, Name, Servers, Topic])
    end.

-spec generate_file_source(map(), map(), map()) -> string().
generate_file_source(Table, Config, _State) ->
    Name = maps:get(name, Table),
    DefaultPath = list_to_binary("/data/" ++ atom_to_list(Name)),
    Path = binary_to_list(maps:get(<<"path">>, Config, DefaultPath)),
    Format = binary_to_list(maps:get(<<"format">>, Config, <<"parquet">>)),
    PartitionBy = maps:get(<<"partition_by">>, Config, []),
    
    PartitionClause = case PartitionBy of
        [] -> "";
        _ -> "\nPARTITIONED BY (" ++ string:join([binary_to_list(P) || P <- PartitionBy], ", ") ++ ")"
    end,
    
    io_lib:format(
"-- File Source: ~s
CREATE OR REPLACE TEMPORARY VIEW ~s
USING ~s
OPTIONS (
  path \"~s\"
)~s;", [Name, Name, Format, Path, PartitionClause]).

-spec generate_kafka_sink(string(), map()) -> string().
generate_kafka_sink(Name, Config) ->
    Servers = string:join(binary_to_list(maps:get(<<"bootstrap_servers">>, Config, [<<"localhost:9092">>])), ","),
    Topic = binary_to_list(maps:get(<<"topic">>, Config, list_to_binary(Name))),
    
    io_lib:format(
"-- Kafka Sink: ~s
-- Write to Kafka using:
-- df.write
--   .format(\"kafka\")
--   .option(\"kafka.bootstrap.servers\", \"~s\")
--   .option(\"topic\", \"~s\")
--   .save()", [Name, Servers, Topic]).

-spec generate_file_sink(string(), map()) -> string().
generate_file_sink(Name, Config) ->
    DefaultPath = list_to_binary("/data/" ++ Name),
    Path = binary_to_list(maps:get(<<"path">>, Config, DefaultPath)),
    Format = binary_to_list(maps:get(<<"format">>, Config, <<"parquet">>)),
    PartitionBy = maps:get(<<"partition_by">>, Config, []),
    Overwrite = maps:get(<<"overwrite">>, Config, false),
    
    Mode = case Overwrite of
        true -> "overwrite";
        false -> "append"
    end,
    
    PartitionClause = case PartitionBy of
        [] -> "";
        _ -> "\n-- .partitionBy(" ++ string:join([binary_to_list(P) || P <- PartitionBy], ", ") ++ ")"
    end,
    
    io_lib:format(
"-- File Sink: ~s
-- Write using:
-- df.write
--   .mode(\"~s\")
--   .format(\"~s\")~s
-- .option(\"path\", \"~s\")
-- .save()", [Name, Mode, Format, PartitionClause, Path]).

-spec create_temp_view(map()) -> string().
create_temp_view(Table) ->
    Name = maps:get(name, Table),
    Cols = string:join(["CAST(NULL AS " ++ base_generator:format_type(T) ++ ") AS " ++ K || {K, T} <- maps:to_list(maps:get(columns, Table, #{}))], ", "),
    io_lib:format("CREATE OR REPLACE TEMPORARY VIEW ~s AS SELECT ~s;", [Name, Cols]).

-spec generate_model_registration(map()) -> string().
generate_model_registration(Model) ->
    Name = maps:get(name, Model),
    Path = maps:get(path, Model),
    InputSchema = maps:get(input_schema, Model),
    OutputSchema = maps:get(output_schema, Model),
    
    io_lib:format(
"-- Model: ~s
-- Path: ~s
-- Input: ~s, Output: ~s
-- spark.udf.register('~s', apply_model('~s'), ~s)", 
        [Name, Path, InputSchema, OutputSchema, Name, Path, OutputSchema]).

-spec generate_view(string(), string(), map()) -> string().
generate_view(Name, Query, _State) ->
    TranslatedQuery = translate_to_spark(Query),
    io_lib:format("CREATE OR REPLACE TEMPORARY VIEW ~s AS\n~s;", [Name, TranslatedQuery]).

-spec translate_to_spark(string()) -> string().
translate_to_spark(Query) ->
    Translations = [
        {"TUMBLE_START(", "window.start, "},
        {"TUMBLE_END(", "window.end, "},
        {"TUMBLE(", "window("},
        {"HOP(", "window("},
        {"SESSION(", "session_window("},
        {"APPLY_MODEL(", "apply_model("},
        {"ENCODE_TEXT(", "encode_text("},
        {"LLM_GENERATE(", "llm_generate("}
    ],
    lists:foldl(fun({From, To}, Acc) -> re:replace(Acc, From, To, [global, {return, list}]) end, Query, Translations).

-spec find_connector(string(), [map()]) -> map() | undefined.
find_connector(_Name, []) ->
    undefined;
find_connector(Name, [C | Rest]) ->
    BinName = maps:get(<<"name">>, C, <<>>),
    case BinName =:= list_to_binary(Name) of
        true -> C;
        false -> find_connector(Name, Rest)
    end.
