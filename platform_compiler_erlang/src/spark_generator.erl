%%% @doc
%%% Spark SQL Code Generator.
%%% Generates Spark SQL code for Batch and Structured Streaming modes.
%%% Includes Airflow DAG generation for orchestration.
%%% @end

-module(spark_generator).

-export([generate_source_ddl/1, generate_sink_ddl/1, generate_transformations/1,
         generate_udf_registrations/1, generate_airflow_dag/1]).

-include("schemas.hrl").

%%====================================================================
%% API functions
%%====================================================================

%% @doc Generate Spark source table DDL.
-spec generate_source_ddl(map()) -> string().
generate_source_ddl(State) ->
    DSL = maps:get(dsl, State),
    Config = maps:get(config, State),
    Sources = maps:get(sources, maps:get(connectors, Config, #{}), []),
    
    Header = "-- ==========================================\n-- SOURCE TABLES\n-- ==========================================",
    TablesDDL = [generate_source_table(T, Sources, State) || T <- maps:get(tables, DSL, [])],
    string:join([Header | TablesDDL], "\n\n").

%% @doc Generate Spark sink table DDL.
-spec generate_sink_ddl(map()) -> string().
generate_sink_ddl(State) ->
    Config = maps:get(config, State),
    Sinks = maps:get(sinks, maps:get(connectors, Config, #{}), []),
    
    Header = "-- ==========================================\n-- SINK TABLES\n-- ==========================================",
    SinksDDL = [generate_sink_table(S, State) || S <- Sinks],
    string:join([Header | SinksDDL], "\n\n").

%% @doc Generate transformation logic (views and queries).
-spec generate_transformations(map()) -> string().
generate_transformations(State) ->
    DSL = maps:get(dsl, State),
    
    Header = "-- ==========================================\n-- TRANSFORMATIONS\n-- ==========================================",
    ViewsDDL = [generate_view(Name, Query, State) || {Name, Query} <- maps:to_list(maps:get(views, DSL, #{}))],
    InsertsDDL = [translate_to_spark(I) ++ ";" || I <- maps:get(inserts, DSL, [])],
    string:join([Header | ViewsDDL ++ InsertsDDL], "\n\n").

%% @doc Generate UDF registration code for Spark.
-spec generate_udf_registrations(map()) -> string().
generate_udf_registrations(State) ->
    DSL = maps:get(dsl, State),
    
    Header = "-- ==========================================\n-- UDF/UDTF REGISTRATIONS\n-- ==========================================",
    ModelsDDL = [generate_model_registration(M) || M <- maps:get(models, DSL, [])],
    Footer = "-- Window function helpers are built-in to Spark SQL",
    string:join([Header | ModelsDDL ++ [Footer]], "\n\n").

%% @doc Generate Airflow DAG Python code for Spark job.
-spec generate_airflow_dag(map()) -> string().
generate_airflow_dag(State) ->
    Config = maps:get(config, State),
    Meta = maps:get(meta, Config, #{}),
    Orch = maps:get(orchestration, Config, #{}),
    Airflow = maps:get(airflow, Orch, undefined),
    Exec = maps:get(execution, Config, #{}),
    Memory = maps:get(memory, Exec, #{}),
    
    DagId = re:replace(maps:get(<<"name">>, Meta, <<"spark_pipeline">>), "-", "_", [global, {return, list}]),
    Owner = binary_to_list(maps:get(<<"owner">>, Meta, <<"data-engineering">>)),
    Desc = binary_to_list(maps:get(<<"description">>, Meta, <<"Spark pipeline">>)),
    Version = binary_to_list(maps:get(<<"version">>, Meta, <<"1.0.0">>)),
    
    ScheduleInterval = case Airflow of
        undefined -> "@daily";
        _ -> binary_to_list(maps:get(<<"schedule_interval">>, Airflow, <<"@daily">>))
    end,
    
    StartDate = case Airflow of
        undefined -> "2024-01-01";
        _ -> binary_to_list(maps:get(<<"start_date">>, Airflow, <<"2024-01-01">>))
    end,
    
    Catchup = case Airflow of
        undefined -> false;
        _ -> maps:get(<<"catchup">>, Airflow, false)
    end,
    
    Retries = case Airflow of
        undefined -> 2;
        _ -> maps:get(<<"retries">>, Airflow, 2)
    end,
    
    Parallelism = maps:get(parallelism, Exec, 1),
    ExecutorMemory = binary_to_list(maps:get(<<"executor">>, Memory, <<"4g">>)),
    DriverMemory = binary_to_list(maps:get(<<"driver">>, Memory, <<"2g">>)),
    
    ShufflePartitions = integer_to_list(Parallelism * 2),
    
    io_lib:format(
"\"\"\"
Airflow DAG for ~s
Generated by Platform Compiler
\"\"\"

from airflow import DAG
from airflow.providers.apache.spark.operators.spark_submit import SparkSubmitOperator
from datetime import datetime, timedelta

default_args = {
    'owner': '~s',
    'depends_on_past': False,
    'email_on_failure': True,
    'email_on_retry': False,
    'retries': ~B,
    'retry_delay': timedelta(minutes=5),
}

dag = DAG(
    '~s',
    default_args=default_args,
    description='~s',
    schedule_interval='~s',
    start_date=datetime(~s),
    catchup=~s,
    tags=['spark', 'sql', '~s'],
)

submit_spark_job = SparkSubmitOperator(
    task_id='run_spark_sql',
    application='hdfs:///scripts/generated/~s.sql',
    conf={
        'spark.sql.shuffle.partitions': '~s',
        'spark.executor.memory': '~s',
        'spark.driver.memory': '~s',
    },
    verbose=True,
    dag=dag,
)",
        [DagId, Owner, Retries, DagId, Desc, ScheduleInterval, 
         re:replace(StartDate, "-", ", ", [global, {return, list}]),
         atom_to_list(Catchup), Version, DagId, ShufflePartitions, 
         ExecutorMemory, DriverMemory]).

